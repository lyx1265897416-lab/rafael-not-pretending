def _drop_clause(text, w):
    """删掉含禁用词的分句（按，；。切）；整句都没了就返回空。"""
    parts = re.split(r'(?<=[，；。,;])', text)
    keep = [p for p in parts if w not in p]
    return ''.join(keep).strip('，；,; ')


def autofix(sp, bad, set_now=None):
    """V1.5 提速：硬规则不合格时由代码就地修，不打回导演层。修不了的留给 lint_left 记录。"""
    fixed = []
    for _, _, b in _beats(sp):
        for w in BANNED:
            if w in b[0]:
                t = _drop_clause(b[0], w)
                b[0] = t if t and w not in t else '两人看着对方，他的目光落在她脸上'; fixed.append('禁用词:' + w)
            if len(b) > 1 and b[1] and w in b[1]: b[1] = 'Come.' if w == 'Follow me' else ''; fixed.append('台词禁用词:' + w)
    for k in ('hold', 'her_hands', 'set'):
        if isinstance(sp.get(k), str):
            for w in BANNED:
                if w in sp[k]: sp[k] = _drop_clause(sp[k], w); fixed.append(k + ':' + w)
    her = [b for _, _, b in _beats(sp) if len(b) > 3 and b[3] == '她' and b[1]]
    for b in her[1:]: b[1] = ''; fixed.append('她多说的一句')
    for b in her[:1]:
        if len(b[1].split()) > 8: b[1] = ' '.join(b[1].split()[:8]).rstrip(',') + '.'
    for k in ('seg1', 'seg2'):
        z = (sp.get('zh') or {}).get(k)
        if isinstance(z, list): sp['zh'][k] = [z[i] if i < len(z) and sp[k][i][1] else '' for i in range(len(sp[k]))]
    props = sp.setdefault('props', []) if isinstance(sp.get('props'), list) else sp.setdefault('props', [])
    for x in bad:
        m = re.match(r'分镜里出现了道具“([^”]+)”', x) or re.match(r'道具“([^”]+)”标的是地点里本来就有', x)
        if m:
            w = m[1]
            if not any(isinstance(p, dict) and w in str(p.get('name', '')) for p in props): props.append({'name': w, 'source': 'scene', 'how': '本来就在两人手边'})
            if w[:2] not in (sp.get('set') or '') and not sp.get('scene_changed'): sp['set'] = (sp.get('set') or set_now or '').rstrip('。') + f'；{w}就在两人手边'
            fixed.append('道具来源:' + w)
    for k in ('A', 'B'):
        o = (sp.get('next') or {}).get(k) or {}
        if str(o.get('zh', '')).rstrip().endswith(('？', '?')): o['zh'] = o['zh'].rstrip().rstrip('？?'); fixed.append('选项问号')
    if sp.get('kiss'):  # 吻戏：软词去掉；只有一拍就在后面补一拍“两人仍在接吻”（按吻戏手册）
        for b in sp.get('seg2', []):
            for w in ('短暂', '克制', '轻轻贴', '一触即分', '缓缓', '慢慢', '呼吸相触'):
                if w in b[0]: b[0] = b[0].replace(w, ''); fixed.append('吻戏软词:' + w)
        kb = [i for i, b in enumerate(sp.get('seg2', [])) if '吻' in str(b[0]) and not str(b[2]).startswith(('插入特写', '特写'))]
        if len(kb) == 1:
            i = kb[0]; sp['seg2'].insert(i + 1, ['两人仍在接吻，他一只手扶着她的后颈，吻得更深，她的手搭在他肩上', '', str(sp['seg2'][i][2]) or '双人近景，固定', ''])
            z = (sp.get('zh') or {}).get('seg2')
            if isinstance(z, list): z.insert(i + 1, '')
            fixed.append('吻戏补一拍')
    sp['autofixed'] = fixed
    return fixed


def trim(sp, mode, bad):
    """打回一次还不合格：每段只保留前两句台词（其余拍的台词清空），长台词截到 10 个词；选项里拉扯的半句删掉（“我上车，要他讲清楚”→“我上车”）；禁用词不自动改，只记录。"""
    import re as _re
    for k in ('A', 'B'):
        o = (sp.get('next') or {}).get(k) or {}
        parts = [x for x in _re.split('[，,：:]', o.get('zh', '')) if x and not any(w in x for w in STALL)]
        if parts and parts != [o.get('zh')]: o['zh'] = '，'.join(parts).rstrip('？?'); o['trimmed'] = True
    for k in ('seg1', 'seg2'):
        n = 0
        for b in sp.get(k, []):
            if b[1]:
                n += 1
                if n > 2: b[1] = ''
                elif len(b[1].split()) > 12: b[1] = ' '.join(b[1].split()[:10]).rstrip(',') + '.'
        z = (sp.get('zh') or {}).get(k)
        if isinstance(z, list): sp['zh'][k] = [z[i] if i < len(z) and sp[k][i][1] else '' for i in range(len(sp[k]))]
    return bad


